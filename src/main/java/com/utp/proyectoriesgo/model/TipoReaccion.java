package com.utp.proyectoriesgo.model;

/**
 * Formas de acompañar una publicación de la comunidad. Son solo de apoyo: no hay «no me gusta»
 * ni nada que pueda herir a quien comparte algo difícil.
 */
public enum TipoReaccion {
    /** «Te abrazo». */
    ABRAZO,
    /** «Eres fuerte». */
    FUERZA,
    /** «Me identifico»: yo también lo he vivido. */
    IDENTIFICO
}
